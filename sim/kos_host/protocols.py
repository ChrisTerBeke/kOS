from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class EngineView(Protocol):
    @property
    def ignition(self) -> bool: ...

    @property
    def flameout(self) -> bool: ...

    @property
    def isp(self) -> float: ...

    @property
    def available_thrust(self) -> float: ...


@runtime_checkable
class ModuleView(Protocol):
    def has_event(self, name: str) -> bool: ...

    def do_event(self, name: str) -> None: ...


@runtime_checkable
class VolumeFileView(Protocol):
    def writeln(self, text: str) -> None: ...


@runtime_checkable
class VolumeView(Protocol):
    def create(self, path: str) -> None: ...

    def open(self, path: str) -> VolumeFileView: ...

    def exists(self, path: str) -> bool: ...


@runtime_checkable
class BodyView(Protocol):
    @property
    def name(self) -> str: ...

    @property
    def mu(self) -> float: ...

    @property
    def radius(self) -> float: ...

    @property
    def rotation_period(self) -> float: ...

    @property
    def atm_height(self) -> float: ...

    def atm_pressure(self, altitude: float) -> float: ...

    def atm_density(self, altitude: float) -> float: ...


@runtime_checkable
class OrbitView(Protocol):
    @property
    def apoapsis(self) -> float: ...

    @property
    def periapsis(self) -> float: ...

    @property
    def eccentricity(self) -> float: ...

    @property
    def inclination(self) -> float: ...

    @property
    def semimajoraxis(self) -> float: ...


@runtime_checkable
class GeoCoordinatesView(Protocol):
    @property
    def lat(self) -> float: ...

    @property
    def lng(self) -> float: ...


@runtime_checkable
class DirectionView(Protocol):
    @property
    def vector(self) -> Any: ...

    @property
    def pitch(self) -> float: ...

    @property
    def yaw(self) -> float: ...

    @property
    def roll(self) -> float: ...


@runtime_checkable
class ShipView(Protocol):
    @property
    def altitude(self) -> float: ...

    @property
    def apoapsis(self) -> float: ...

    @property
    def periapsis(self) -> float: ...

    @property
    def mass(self) -> float: ...

    @property
    def available_thrust(self) -> float: ...

    @property
    def maxthrust(self) -> float: ...

    @property
    def vertical_speed(self) -> float: ...

    @property
    def groundspeed(self) -> float: ...

    @property
    def q(self) -> float: ...

    @property
    def body(self) -> BodyView: ...

    @property
    def orbit(self) -> OrbitView: ...

    @property
    def geoposition(self) -> GeoCoordinatesView: ...

    @property
    def facing(self) -> DirectionView: ...

    @property
    def prograde(self) -> DirectionView: ...

    @property
    def srfprograde(self) -> DirectionView: ...

    @property
    def up(self) -> DirectionView: ...

    @property
    def north(self) -> DirectionView: ...

    @property
    def deltav_vacuum(self) -> float: ...

    def engines(self) -> list[EngineView]: ...

    def modules_named(self, name: str) -> list[ModuleView]: ...


@runtime_checkable
class KosHost(Protocol):
    """World + craft + I/O surface the VM may call. No physics types leak upward."""

    def advance(self, dt: float) -> None:
        """Advance simulated universe time by dt seconds."""

    @property
    def time_seconds(self) -> float: ...

    @property
    def mission_time(self) -> float: ...

    @property
    def ship(self) -> ShipView: ...

    @property
    def body(self) -> BodyView: ...

    def eta_apoapsis(self) -> float: ...

    def eta_periapsis(self) -> float: ...

    def set_throttle_lock(self, expression: Any | None) -> None: ...

    def set_steering_lock(self, expression: Any | None) -> None: ...

    def evaluate_throttle(self) -> float: ...

    def evaluate_steering(self) -> Any: ...

    def stage(self) -> None: ...

    def set_rcs(self, enabled: bool) -> None: ...

    def set_sas(self, enabled: bool) -> None: ...

    def set_abort(self, enabled: bool) -> None: ...

    def neutralize_controls(self) -> None: ...

    def volume(self, id: int) -> VolumeView: ...

    def switch_to(self, volume: VolumeView) -> None: ...

    def resolve_path(self, path: str) -> str: ...

    def read_script(self, path: str) -> str: ...

    def path_exists(self, path: str) -> bool: ...

    def copy_path(self, src: str, dst: str) -> None: ...

    def delete_path(self, path: str) -> None: ...

    def push_terminal_char(self, ch: str) -> None: ...

    def terminal_has_char(self) -> bool: ...

    def terminal_get_char(self) -> str: ...

    def snapshot(self) -> dict[str, Any]: ...
